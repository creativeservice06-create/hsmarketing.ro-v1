'use client';

import { useEffect, useRef, useState } from 'react';
import Link from 'next/link';
import { Analytics } from '@vercel/analytics/next';
import styles from './CookieConsent.module.css';

/**
 * Hard Service cookie consent — GTM is NOT downloaded before analytics or
 * marketing consent. This controls GTM and Vercel Analytics only.
 * Other tracking scripts and GTM tags need separate consent configuration.
 */
const STORAGE_KEY = 'hs-cookie-preferences-v1';
const CONSENT_LIFETIME_MS = 180 * 24 * 60 * 60 * 1000;
const OPEN_EVENT = 'hs:open-cookie-settings';

type Preferences = {
  analytics: boolean;
  marketing: boolean;
  savedAt: number;
};
type Draft = Pick<Preferences, 'analytics' | 'marketing'>;

declare global {
  interface Window {
    dataLayer?: unknown[];
  }
}

function readPreferences(): Preferences | null {
  try {
    const raw = window.localStorage.getItem(STORAGE_KEY);
    if (!raw) return null;
    const value: unknown = JSON.parse(raw);
    if (!value || typeof value !== 'object') return null;
    const parsed = value as Partial<Preferences>;
    if (
      typeof parsed.analytics !== 'boolean' ||
      typeof parsed.marketing !== 'boolean' ||
      typeof parsed.savedAt !== 'number' ||
      !Number.isFinite(parsed.savedAt) ||
      Date.now() - parsed.savedAt > CONSENT_LIFETIME_MS ||
      parsed.savedAt > Date.now()
    ) return null;
    return parsed as Preferences;
  } catch {
    return null;
  }
}

function consentFields(preferences: Draft) {
  return {
    ad_storage: preferences.marketing ? 'granted' : 'denied',
    ad_user_data: preferences.marketing ? 'granted' : 'denied',
    ad_personalization: preferences.marketing ? 'granted' : 'denied',
    analytics_storage: preferences.analytics ? 'granted' : 'denied',
    functionality_storage: 'denied',
    personalization_storage: 'denied',
    security_storage: 'granted',
  };
}

function pushConsent(command: 'default' | 'update', fields: ReturnType<typeof consentFields>) {
  window.dataLayer = window.dataLayer || [];
  // GTM/Google tag reads commands in the format generated by gtag().
  function gtag(_type: 'consent', _command: 'default' | 'update', _fields: ReturnType<typeof consentFields>) {
    window.dataLayer!.push(arguments);
  }
  gtag('consent', command, fields);
}

function applyTracking(preferences: Draft, gtmId: string) {
  const hasConsent = preferences.analytics || preferences.marketing;
  const scriptExists = !!document.querySelector('script[data-hs-consent-gtm="true"]');

  if (scriptExists) {
    pushConsent('update', consentFields(preferences));
    window.dataLayer?.push({
      event: 'hs_cookie_consent_updated',
      hs_analytics_consent: preferences.analytics,
      hs_marketing_consent: preferences.marketing,
    });
    return;
  }

  // Basic consent mode: the GTM script is not requested without an opt-in.
  if (!hasConsent || !/^GTM-[A-Z0-9]+$/.test(gtmId)) return;

  // IMPORTANT: these two entries must be pushed BEFORE GTM is downloaded.
  pushConsent('default', consentFields({ analytics: false, marketing: false }));
  pushConsent('update', consentFields(preferences));
  window.dataLayer!.push({
    'gtm.start': Date.now(),
    event: 'gtm.js',
    hs_analytics_consent: preferences.analytics,
    hs_marketing_consent: preferences.marketing,
  });

  const script = document.createElement('script');
  script.async = true;
  script.dataset.hsConsentGtm = 'true';
  script.src = `https://www.googletagmanager.com/gtm.js?id=${encodeURIComponent(gtmId)}`;
  document.head.appendChild(script);
}

export default function CookieConsent({ gtmId = '' }: { gtmId?: string }) {
  const [ready, setReady] = useState(false);
  const [saved, setSaved] = useState<Preferences | null>(null);
  const [showSettings, setShowSettings] = useState(false);
  const [draft, setDraft] = useState<Draft>({ analytics: false, marketing: false });
  const closeButtonRef = useRef<HTMLButtonElement>(null);

  useEffect(() => {
    const value = readPreferences();
    setSaved(value);
    if (value) {
      setDraft({ analytics: value.analytics, marketing: value.marketing });
      applyTracking(value, gtmId);
    }
    setReady(true);
  }, [gtmId]);

  useEffect(() => {
    const open = () => {
      const current = readPreferences();
      setDraft({
        analytics: current?.analytics ?? false,
        marketing: current?.marketing ?? false,
      });
      setShowSettings(true);
    };
    window.addEventListener(OPEN_EVENT, open);
    return () => window.removeEventListener(OPEN_EVENT, open);
  }, []);

  useEffect(() => {
    if (!showSettings) return;
    closeButtonRef.current?.focus();
    const onEscape = (event: KeyboardEvent) => {
      if (event.key === 'Escape') setShowSettings(false);
    };
    window.addEventListener('keydown', onEscape);
    return () => window.removeEventListener('keydown', onEscape);
  }, [showSettings]);

  useEffect(() => {
    document.body.classList.toggle('hs-cookie-consent-visible', ready && (!saved || showSettings));
    return () => document.body.classList.remove('hs-cookie-consent-visible');
  }, [ready, saved, showSettings]);

  function save(draftValue: Draft) {
    const previous = readPreferences();
    const updated: Preferences = { ...draftValue, savedAt: Date.now() };
    try {
      window.localStorage.setItem(STORAGE_KEY, JSON.stringify(updated));
    } catch {
      // Consent choice still applies for this page if storage is disabled.
    }
    setSaved(updated);
    setDraft(draftValue);
    setShowSettings(false);

    const consentRevoked =
      (previous?.analytics && !updated.analytics) ||
      (previous?.marketing && !updated.marketing);

    // A loaded third-party script cannot reliably be unloaded: reload the page
    // after consent withdrawal so it is no longer requested.
    if (consentRevoked) {
      window.location.reload();
      return;
    }
    applyTracking(updated, gtmId);
  }

  if (!ready) return null;

  return <>
    {saved?.analytics && <Analytics />}

    {!saved && !showSettings && (
      <section
        className={styles.banner}
        aria-label="Preferințe pentru cookie-uri"
        aria-describedby="hs-cookie-description"
      >
        <div className={styles.bannerText}>
          <p id="hs-cookie-description">
            Folosim cookie-uri esențiale pentru funcționarea site-ului. Doar cu acordul tău
            activăm statisticile și măsurarea reclamelor.{' '}
            <Link href="/politica-cookie-uri/" className={styles.policyLink}>Află mai multe.</Link>{' '}
            <button
              type="button"
              className={styles.settingsInline}
              onClick={() => setShowSettings(true)}
            >
              Personalizează.
            </button>
          </p>
        </div>
        <div className={styles.actions}>
          <button
            type="button"
            className={styles.secondary}
            onClick={() => save({ analytics: false, marketing: false })}
          >
            Doar esențiale
          </button>
          <button
            type="button"
            className={styles.primary}
            onClick={() => save({ analytics: true, marketing: true })}
          >
            Accept toate
          </button>
        </div>
      </section>
    )}

    {showSettings && <div className={styles.backdrop}>
      <section className={styles.dialog} role="dialog" aria-modal="true" aria-labelledby="hs-cookie-settings-title" aria-describedby="hs-cookie-settings-desc">
        <div className={styles.dialogTop}>
          <div>
            <div className={styles.eyebrow}>PREFERINȚE DE CONFIDENȚIALITATE</div>
            <h2 id="hs-cookie-settings-title">Setări cookie-uri</h2>
          </div>
          <button ref={closeButtonRef} type="button" className={styles.close} aria-label="Închide setările" onClick={() => setShowSettings(false)}>×</button>
        </div>
        <p id="hs-cookie-settings-desc">Alege ce categorii opționale permiți. Cookie-urile necesare nu pot fi dezactivate de aici.</p>
        <div className={styles.category}>
          <div><strong>Necesare</strong><p>Elemente esențiale pentru funcționarea site-ului și păstrarea alegerii tale.</p></div>
          <span className={styles.always}>Mereu active</span>
        </div>
        <label className={styles.category}>
          <span><strong>Statistici</strong><p>Măsurarea vizitelor și a interacțiunilor prin instrumentele de analiză configurate.</p></span>
          <input type="checkbox" checked={draft.analytics} onChange={event => setDraft(old => ({ ...old, analytics: event.target.checked }))}/>
        </label>
        <label className={styles.category}>
          <span><strong>Marketing</strong><p>Măsurarea și optimizarea reclamelor, inclusiv prin platformele conectate în GTM.</p></span>
          <input type="checkbox" checked={draft.marketing} onChange={event => setDraft(old => ({ ...old, marketing: event.target.checked }))}/>
        </label>
        <div className={styles.dialogActions}>
          <button type="button" className={styles.secondary} onClick={() => save({ analytics: false, marketing: false })}>Respinge toate</button>
          <button type="button" className={styles.primary} onClick={() => save(draft)}>Salvează preferințele</button>
        </div>
        <p className={styles.footnote}>Poți schimba ulterior alegerea din subsolul site-ului: „Setări cookie-uri”.</p>
      </section>
    </div>}
  </>;
}

/** Insert <CookiePreferencesButton /> in your existing Footer.tsx. */
export function CookiePreferencesButton() {
  return <button
    className={styles.footerButton}
    type="button"
    onClick={() => window.dispatchEvent(new Event(OPEN_EVENT))}
  >Setări cookie-uri</button>;
}
